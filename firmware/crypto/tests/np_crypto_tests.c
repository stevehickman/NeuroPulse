/*
 * NeuroPulse np_crypto — Host Smoke Tests (TDD)
 * Document: NP-SW-001 §9.4 (SW-01-M07 Ed25519 dependency)
 *
 * RFC 8032 §6 Ed25519 test vectors (TV1, TV2).
 * NIST FIPS 180-4 SHA-256 / SHA-512 test vectors.
 * IEEE 802.3 CRC-32 test vector ("123456789" → 0xCBF43926).
 *
 * Phase 1 (RED): all positive-behavior tests FAIL against stub.
 * Phase 2 (GREEN): all tests PASS after real implementation.
 *
 * IEC 62304 Class C — np_crypto consumed by SW-01 (safety MCU).
 * Test binary runs on host; not a hardware test.
 */

#include "np_crypto.h"

#include <stdint.h>
#include <string.h>
#include <stdio.h>

static int g_failures = 0;

static void check(int cond, const char *name)
{
    if (cond) {
        printf("PASS: %s\n", name);
    } else {
        printf("FAIL: %s\n", name);
        g_failures++;
    }
}

static void check_bytes(const uint8_t *expected, const uint8_t *got,
                         uint32_t len, const char *name)
{
    int ok = (memcmp(expected, got, (size_t)len) == 0);
    check(ok, name);
    if (!ok) {
        uint32_t i;
        printf("  Expected: ");
        for (i = 0U; i < len; i++) { printf("%02x", expected[i]); }
        printf("\n  Got:      ");
        for (i = 0U; i < len; i++) { printf("%02x", got[i]); }
        printf("\n");
    }
}

