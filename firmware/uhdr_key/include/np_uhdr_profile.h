/*
 * NeurOne Per-Person UHDR Keys on a Shared Helmet — profile key store
 * Document: NP-FW-EMMC-002 §C.8 (OI-PRIV-34, NP-PRIV-ANALYSIS-004)
 * IEC 62304 Class: SW-02 Class B (main processor)
 *
 * The principal ruled on 2026-11-23 that helmets are shared and that each
 * person's UHDR is sealed under that person's own key (§C.8.1).  This module is
 * the first increment of that design: the per-person KEY STORE.  It does not yet
 * seal files, export files or change the UHDR mount; those are later increments
 * (§C.8, "Built").
 *
 * Per profile (one slot each, at most NP_UHDR_PROFILE_MAX):
 *
 *   PK        32-byte profile key, TRNG.  Never stored in the clear.
 *   wrap 1    PK under WKMD = hw_bind(Argon2id(credential, salt), fused key),
 *             exactly the §C.2 wrapper-key derivation.  Opens PK on THIS helmet
 *             only: a copied record is useless elsewhere (privacy review F1).
 *   wrap 2    PK under RK = recovery_kdf(recovery code, rec_salt).  Travels in
 *             every export.  Re-binds PK to another helmet.
 *   recovery  16 bytes (128 bits) from the TRNG, generated by the helmet and
 *   code      returned ONCE, at create.  Never written to Config, never to SHDR.
 *             The caller shows it to the person and hands it to their phone's
 *             presence-gated store, then zeroes it (§C.8.1, Q3b).
 *
 * A record is LIVE (wrap 1 and wrap 2 present) or DORMANT (wrap 2 only: an
 * imported profile not yet re-bound on this helmet).  A dormant profile opens
 * only with its recovery code (np_uhdr_profile_rebind).
 *
 * Every attempt that reaches a KDF (unlock and rebind) is limited PER PROFILE
 * (the principal, 2026-11-24): the failed-attempt count lives in that
 * profile's own record and is charged before the secret is tested, and the
 * back-off is the §C.7 schedule measured from that profile's last charged
 * attempt (REQ-EMMC2-05).  One person's wrong guesses never lock out another.
 * An attacker gets the free attempts once per profile, but does not know how
 * many profiles hold data.
 *
 * The profile key lives only in a caller-owned np_uhdr_profile_ctx_t while the
 * profile is open, and is zeroed by np_uhdr_profile_close() and on every
 * failure path.
 */

#ifndef NP_UHDR_PROFILE_H
#define NP_UHDR_PROFILE_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "np_uhdr_key_config.h"
#include "np_uhdr_key_types.h"

/* ── Constants (§C.8.2) ──────────────────────────────────────────────────── */

#define NP_UHDR_PROFILE_KEY_LEN        32U  /* PK                              */
#define NP_UHDR_PROFILE_ID_LEN         16U  /* opaque id; never a name          */
#define NP_UHDR_RECOVERY_CODE_LEN      16U  /* 128 bits: NIST SP 800-57 Pt 1    */
#define NP_UHDR_RECOVERY_SALT_LEN      16U
#define NP_UHDR_RECOVERY_KEY_LEN       32U  /* RK, wraps PK                     */

/*
 * Most profiles one helmet holds: 24 (the principal, 2026-11-24).  Profiles
 * are loaded from the app as needed, so the most a helmet holds at once is a
 * clinic day's patients, and a clinic runs at most 24 sessions a day.  That
 * figure is an assumption, not a measurement (UC-204).  Cost of changing it:
 * one Config record (NP_UHDR_PROFILE_RECORD_SIZE) per profile in the 16 MiB
 * Config partition, plus 8 bytes of RAM per slot for the back-off reference.
 */
#define NP_UHDR_PROFILE_MAX            24U

#define NP_UHDR_PROFILE_MAGIC          0x5250504EU  /* "NPPR", little-endian */
#define NP_UHDR_PROFILE_FORMAT         1U

typedef enum {
    NP_UHDR_PROFILE_LIVE    = 1,   /* wrap 1 + wrap 2                       */
    NP_UHDR_PROFILE_DORMANT = 2    /* wrap 2 only: imported, not re-bound   */
} np_uhdr_profile_state_t;

/*
 * One profile's Config record (Config partition, one named file per slot).
 * Packed and byte-exact so the on-flash image is stable across toolchains:
 *   4+4+1+3+4 + 16 + 32+16 + 12+32+16 + 16 + 12+32+16 = 216 bytes.
 * Fleet-export prohibition: as np_ukmd_record_t, nothing here may reach SHDR,
 * the fleet database or a diagnostic export.  The only export is
 * np_uhdr_profile_export(), which removes wrap 1 and its salt.
 */
typedef struct __attribute__((packed)) {
    uint32_t magic;                                  /* NP_UHDR_PROFILE_MAGIC  */
    uint32_t format;                                 /* NP_UHDR_PROFILE_FORMAT */
    uint8_t  state;                                  /* np_uhdr_profile_state_t */
    uint8_t  reserved0[3];                           /* zero                   */
    uint32_t failed_attempts;                        /* §C.8 per-profile limit;
                                                        not authenticated, zero
                                                        in every export        */
    uint8_t  profile_id[NP_UHDR_PROFILE_ID_LEN];
    /* wrap 1 (unlock): device-bound */
    uint8_t  kdf_salt[NP_UHDR_SALT_LEN];
    uint32_t argon2id_version;
    uint32_t argon2id_m_cost;
    uint32_t argon2id_t_cost;
    uint32_t argon2id_parallelism;
    uint8_t  w1_nonce[NP_UHDR_GCM_NONCE_LEN];
    uint8_t  w1_ct[NP_UHDR_PROFILE_KEY_LEN];
    uint8_t  w1_tag[NP_UHDR_GCM_TAG_LEN];
    /* wrap 2 (recovery): portable */
    uint8_t  rec_salt[NP_UHDR_RECOVERY_SALT_LEN];
    uint8_t  w2_nonce[NP_UHDR_GCM_NONCE_LEN];
    uint8_t  w2_ct[NP_UHDR_PROFILE_KEY_LEN];
    uint8_t  w2_tag[NP_UHDR_GCM_TAG_LEN];
} np_uhdr_profile_record_t;

#define NP_UHDR_PROFILE_RECORD_SIZE    216U

/* An export is a record in the DORMANT state with every wrap-1 field zero. */
typedef np_uhdr_profile_record_t np_uhdr_profile_export_t;

/* An open profile.  `pk` is valid only while `open` is true. */
typedef struct {
    uint8_t pk[NP_UHDR_PROFILE_KEY_LEN];             /* SRAM only             */
    uint8_t profile_id[NP_UHDR_PROFILE_ID_LEN];
    uint8_t slot;
    bool    open;
} np_uhdr_profile_ctx_t;

/* ── API ──────────────────────────────────────────────────────────────────── */

/*
 * Create a profile in an empty slot.  Generates PK, the profile id, the
 * recovery code and both wraps, writes the record and leaves the profile open.
 * `recovery_code_out` receives the code ONCE; the caller must zero it after
 * handing it on.  Refuses an occupied slot (NP_UHDR_ERR_EXISTS).
 */
np_uhdr_status_t np_uhdr_profile_create(uint8_t slot,
                                        const uint8_t *credential, size_t cred_len,
                                        np_uhdr_profile_ctx_t *ctx,
                                        uint8_t recovery_code_out[NP_UHDR_RECOVERY_CODE_LEN]);

/*
 * Open a LIVE profile with its unlock credential.  Charged to that profile's
 * own attempt count.  A DORMANT profile is refused with NP_UHDR_ERR_STATE
 * without running the KDF or being charged.
 */
np_uhdr_status_t np_uhdr_profile_unlock(uint8_t slot,
                                        const uint8_t *credential, size_t cred_len,
                                        np_uhdr_profile_ctx_t *ctx);

/*
 * Open a profile with its recovery code and bind it to THIS helmet under a new
 * unlock credential: opens PK with wrap 2, writes a fresh wrap 1, and leaves
 * the record LIVE and the profile open.  Used after an import (a replacement
 * helmet, or a person's own helmet) and for a forgotten credential.  Charged
 * to that profile's own attempt count.
 */
np_uhdr_status_t np_uhdr_profile_rebind(uint8_t slot,
                                        const uint8_t recovery_code[NP_UHDR_RECOVERY_CODE_LEN],
                                        const uint8_t *new_credential, size_t new_cred_len,
                                        np_uhdr_profile_ctx_t *ctx);

/*
 * Re-wrap an open profile's PK under a new unlock credential (fresh salt and
 * nonce).  Wrap 2, the recovery code and every sealed file are unchanged.
 */
np_uhdr_status_t np_uhdr_profile_change_credential(np_uhdr_profile_ctx_t *ctx,
                                                   const uint8_t *new_credential,
                                                   size_t new_cred_len);

/* Close an open profile: zero PK.  Safe on a closed or NULL context. */
void np_uhdr_profile_close(np_uhdr_profile_ctx_t *ctx);

/*
 * Export a slot for backup or transfer (§C.8.4).  Needs no credential: the
 * export carries wrap 2 only, so whoever holds it can read nothing without
 * the person's recovery code.  Wrap 1 and its salt and parameters, and the
 * failed-attempt count, are zeroed and the state is DORMANT.  Re-importing an
 * export cannot reset a credential's count to help a guesser: a dormant
 * profile does not take the credential at all, only the recovery code.
 */
np_uhdr_status_t np_uhdr_profile_export(uint8_t slot, np_uhdr_profile_export_t *out);

/*
 * Import an export into an EMPTY slot as a DORMANT profile.  Refuses an
 * occupied slot, a malformed export, and an export that carries any wrap-1
 * byte.  The profile opens only after np_uhdr_profile_rebind().
 */
np_uhdr_status_t np_uhdr_profile_import(uint8_t slot, const np_uhdr_profile_export_t *in);

/*
 * Delete a profile: destroys its record, so PK can never be opened again on
 * this helmet.  Zeroes `ctx` if it is open on that slot (may be NULL).  An
 * erase, which CLAUDE.md §5.1 does not count as a weakening.
 */
np_uhdr_status_t np_uhdr_profile_delete(uint8_t slot, np_uhdr_profile_ctx_t *ctx);

/* ── Platform seams (NP-FW-EMMC-002 §C.8; OI-UHDRK-10..13) ──────────────────
 * Declared once, here; trap-defined in firmware/platform/src/np_platform_stub.c
 * until the Config store and the CAAM KDF are wired.
 */

/* OI-UHDRK-10: read the record of profile slot `profile`.  NP_UHDR_ERR_EMPTY when the slot is empty. */
extern np_uhdr_status_t np_uhdr_hal_profile_read(uint8_t profile, np_uhdr_profile_record_t *out);

/* OI-UHDRK-11: atomically write slot's record (LittleFS transaction). */
extern np_uhdr_status_t np_uhdr_hal_profile_write(uint8_t profile, const np_uhdr_profile_record_t *rec);

/* OI-UHDRK-12: remove slot's record.  Removing an empty slot succeeds. */
extern np_uhdr_status_t np_uhdr_hal_profile_erase(uint8_t profile);

/*
 * OI-UHDRK-13: RK = KDF(recovery code, rec_salt), 32 bytes.  The code carries
 * 128 bits from the TRNG, so no stretching is needed; the construction (for
 * example HKDF-SHA-256) is the cryptography reviewer's (OI-EMMC2-02).
 */
extern np_uhdr_status_t np_uhdr_hal_recovery_kdf(const uint8_t code[NP_UHDR_RECOVERY_CODE_LEN],
                                                 const uint8_t salt[NP_UHDR_RECOVERY_SALT_LEN],
                                                 uint8_t rk_out[NP_UHDR_RECOVERY_KEY_LEN]);

#endif /* NP_UHDR_PROFILE_H */
