// ── Localized strings (CLAUDE.md §17) ─────────────────────────────────────────
// Compose Multiplatform resources read the same values*/strings.xml the Android app does. They are generated
// from locales/*.json into the build directory (never checked in) and handed to the resource plugin as a
// custom directory, so there is still exactly one committed copy of every string.
val repoRoot: java.io.File = rootProject.projectDir.parentFile.parentFile
val generatedLocaleRes: Provider<Directory> = layout.buildDirectory.dir("generated/composeResources/locales")

val syncLocales by tasks.registering(Exec::class) {
    group = "localization"
    description = "Generate Compose Multiplatform values*/strings.xml from canonical locales/*.json"
    inputs.dir(File(repoRoot, "locales")).withPathSensitivity(PathSensitivity.RELATIVE)
    inputs.file(File(repoRoot, "scripts/sync-locales.ts")).withPathSensitivity(PathSensitivity.RELATIVE)
    outputs.dir(generatedLocaleRes)
    // The script only writes; a directory left by an earlier run (or an earlier qualifier scheme) must not survive it.
    doFirst { delete(generatedLocaleRes) }
    workingDir = repoRoot
    commandLine("bun", "scripts/sync-locales.ts", "--compose-res=${generatedLocaleRes.get().asFile.absolutePath}")
}

// ── The validator's message table ────────────────────────────────────────────
// Compose Multiplatform 1.7 cannot enumerate its string resources, and the validator's messages are looked up by
// key at run time (NPValidationText), so the table of those keys is generated from locales/en.json.
val generatedValidationDir = layout.buildDirectory.dir("generated/validation/commonMain/kotlin")
val generateValidationStrings by tasks.registering {
    description = "Writes ValidationStrings.kt: validator locale keys to their Compose resources."
    group = "localization"
    val enJson = File(repoRoot, "locales/en.json")
    inputs.file(enJson)
    outputs.dir(generatedValidationDir)
    doLast {
        val keys = Regex("\"((?:VALIDATE_|SOCKET_ERR)[A-Z0-9_]*)\"\\s*:").findAll(enJson.readText()).map { it.groupValues[1] }.toSortedSet()
        val out = generatedValidationDir.get().asFile.resolve("life/neurone/shared/ui/ValidationStrings.kt")
        out.parentFile.mkdirs()
        out.writeText(buildString {
            appendLine("// GENERATED by :shared generateValidationStrings from locales/en.json — do not edit.")
            appendLine("package life.neurone.shared.ui")
            appendLine()
            appendLine("import life.neurone.shared.resources.Res")
            appendLine("import life.neurone.shared.resources.*")
            appendLine("import org.jetbrains.compose.resources.StringResource")
            appendLine()
            appendLine("object ValidationStrings {")
            appendLine("    val all: Map<String, StringResource> = mapOf(")
            for (k in keys) appendLine("        \"${k.lowercase()}\" to Res.string.${k.lowercase()},")
            appendLine("    )")
            appendLine("}")
        })
    }
}

// The cloud providers' client registrations (SWR-MG-19), from the build and not from source: a client ID is registered by the
// owner with each provider, and none exists yet. Gradle property or environment variable; a provider whose required values are not
// all set is null in the config, and a sign-in to it fails with NOT_CONFIGURED naming it. Written to CloudAuthBuildConfig.kt.
//   Google:    cloudAuth.google.clientId     CLOUDAUTH_GOOGLE_CLIENT_ID      (required)
//              cloudAuth.google.redirectUri  CLOUDAUTH_GOOGLE_REDIRECT_URI   (required)
//              cloudAuth.google.clientSecret CLOUDAUTH_GOOGLE_CLIENT_SECRET  (optional: a desktop-type client only)
//   Microsoft: cloudAuth.microsoft.clientId / .redirectUri (required), .oneDriveTenant / .azureTenant (optional)
//              CLOUDAUTH_MICROSOFT_CLIENT_ID / _REDIRECT_URI / _ONEDRIVE_TENANT / _AZURE_TENANT
//   Dropbox:   cloudAuth.dropbox.appKey / .redirectUri (required)   CLOUDAUTH_DROPBOX_APP_KEY / _REDIRECT_URI
//   CloudKit:  cloudAuth.cloudKit.container / .apiToken / .signInCallbackUri (required), .environment / .baseUrl (optional)
//              CLOUDAUTH_CLOUDKIT_CONTAINER / _API_TOKEN / _SIGN_IN_CALLBACK_URI / _ENVIRONMENT / _BASE_URL
fun cloudAuthInput(property: String, env: String): String? =
    ((findProperty(property) as String?) ?: System.getenv(env))?.trim()?.takeIf { it.isNotEmpty() }

fun kotlinLiteral(value: String): String = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""

val cloudAuthConfigSource: String = run {
    val gId = cloudAuthInput("cloudAuth.google.clientId", "CLOUDAUTH_GOOGLE_CLIENT_ID")
    val gRedirect = cloudAuthInput("cloudAuth.google.redirectUri", "CLOUDAUTH_GOOGLE_REDIRECT_URI")
    val gSecret = cloudAuthInput("cloudAuth.google.clientSecret", "CLOUDAUTH_GOOGLE_CLIENT_SECRET")
    val mId = cloudAuthInput("cloudAuth.microsoft.clientId", "CLOUDAUTH_MICROSOFT_CLIENT_ID")
    val mRedirect = cloudAuthInput("cloudAuth.microsoft.redirectUri", "CLOUDAUTH_MICROSOFT_REDIRECT_URI")
    val mOneDrive = cloudAuthInput("cloudAuth.microsoft.oneDriveTenant", "CLOUDAUTH_MICROSOFT_ONEDRIVE_TENANT")
    val mAzure = cloudAuthInput("cloudAuth.microsoft.azureTenant", "CLOUDAUTH_MICROSOFT_AZURE_TENANT")
    val dbKey = cloudAuthInput("cloudAuth.dropbox.appKey", "CLOUDAUTH_DROPBOX_APP_KEY")
    val dbRedirect = cloudAuthInput("cloudAuth.dropbox.redirectUri", "CLOUDAUTH_DROPBOX_REDIRECT_URI")
    val ckContainer = cloudAuthInput("cloudAuth.cloudKit.container", "CLOUDAUTH_CLOUDKIT_CONTAINER")
    val ckToken = cloudAuthInput("cloudAuth.cloudKit.apiToken", "CLOUDAUTH_CLOUDKIT_API_TOKEN")
    val ckCallback = cloudAuthInput("cloudAuth.cloudKit.signInCallbackUri", "CLOUDAUTH_CLOUDKIT_SIGN_IN_CALLBACK_URI")
    val ckEnvironment = cloudAuthInput("cloudAuth.cloudKit.environment", "CLOUDAUTH_CLOUDKIT_ENVIRONMENT")
    val ckBase = cloudAuthInput("cloudAuth.cloudKit.baseUrl", "CLOUDAUTH_CLOUDKIT_BASE_URL")
    fun arg(name: String, value: String?) = if (value != null) "$name = ${kotlinLiteral(value)}" else null
    val google = if (gId != null && gRedirect != null) {
        "OAuthClientConfig(" + listOfNotNull(arg("clientId", gId), arg("redirectUri", gRedirect), arg("clientSecret", gSecret)).joinToString(", ") + ")"
    } else "null"
    val microsoft = if (mId != null && mRedirect != null) {
        "MicrosoftClientConfig(" + listOfNotNull(arg("clientId", mId), arg("redirectUri", mRedirect), arg("oneDriveTenant", mOneDrive), arg("azureTenant", mAzure)).joinToString(", ") + ")"
    } else "null"
    val dropbox = if (dbKey != null && dbRedirect != null) {
        "DropboxClientConfig(" + listOfNotNull(arg("appKey", dbKey), arg("redirectUri", dbRedirect)).joinToString(", ") + ")"
    } else "null"
    val cloudKit = if (ckContainer != null && ckToken != null && ckCallback != null) {
        "CloudKitConfig(" + listOfNotNull(arg("container", ckContainer), arg("apiToken", ckToken), arg("signInCallbackUri", ckCallback), arg("environment", ckEnvironment), arg("baseUrl", ckBase)).joinToString(", ") + ")"
    } else "null"
    buildString {
        appendLine("// GENERATED by :shared generateCloudAuthConfig from Gradle properties and environment variables — do not edit, do not commit.")
        appendLine("package life.neurone.shared")
        appendLine()
        appendLine("import life.neurone.core.cloudauth.CloudAuthConfig")
        appendLine("import life.neurone.core.cloudauth.CloudKitConfig")
        appendLine("import life.neurone.core.cloudauth.DropboxClientConfig")
        appendLine("import life.neurone.core.cloudauth.MicrosoftClientConfig")
        appendLine("import life.neurone.core.cloudauth.OAuthClientConfig")
        appendLine()
        appendLine("/** The cloud providers this build was registered with; a provider left out here is null and its sign-in fails with NOT_CONFIGURED. */")
        appendLine("object CloudAuthBuildConfig {")
        appendLine("    val config: CloudAuthConfig = CloudAuthConfig(google = $google, microsoft = $microsoft, cloudKit = $cloudKit, dropbox = $dropbox)")
        appendLine("}")
    }
}
val generatedCloudAuthDir = layout.buildDirectory.dir("generated/cloudauth/commonMain/kotlin")
val generateCloudAuthConfig by tasks.registering {
    description = "Writes CloudAuthBuildConfig.kt: the cloud providers' client registrations, from the build."
    group = "build"
    inputs.property("source", cloudAuthConfigSource)
    outputs.dir(generatedCloudAuthDir)
    doLast {
        val out = generatedCloudAuthDir.get().asFile.resolve("life/neurone/shared/CloudAuthBuildConfig.kt")
        out.parentFile.mkdirs()
        out.writeText(cloudAuthConfigSource)
    }
}

kotlin {
    androidTarget {
        compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
    }
    jvm("desktop") {
        compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
    }
    @OptIn(ExperimentalWasmDsl::class)
    wasmJs { browser() }
    listOf(iosArm64(), iosSimulatorArm64()).forEach {
        it.binaries.framework {
            baseName = "NeurOneShared"
            isStatic = true
        }
    }

    // The local-network link (SWR-MG-10) needs sockets, which Ktor has for the JVM and iOS but not for the browser. Its code
    // lives in `socketsMain`, shared by Android, the desktop and iOS, so it is written once and the web build never sees it.
    @OptIn(org.jetbrains.kotlin.gradle.ExperimentalKotlinGradlePluginApi::class)
    applyDefaultHierarchyTemplate {
        common {
            group("sockets") {
                withAndroidTarget()
                withJvm()
                // The default template's own `ios` group (iosMain), not only its two targets: code in iosMain
                // (IosPlatformServices) reads LanLinkTransport, and a target's source set is not visible from iosMain.
                group("ios")
            }
        }
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generateValidationStrings.map { generatedValidationDir.get() })
            kotlin.srcDir(generateCloudAuthConfig.map { generatedCloudAuthDir.get() })
        }
        commonMain.dependencies {
            api(project(":core"))
            // Sign-in to the cloud providers (SWR-MG-19): the iOS browser session is in iosMain.
            implementation(project(":cloudauth"))
            implementation(compose.runtime)
            implementation(compose.foundation)
            implementation(compose.ui)
            implementation(compose.material3)
            implementation(compose.components.resources)
            implementation("org.jetbrains.compose.material:material-icons-core:1.7.3")
            api("org.jetbrains.kotlinx:kotlinx-coroutines-core:1.9.0")
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
        // Created by the hierarchy template above, so configured by name once it exists.
        matching { it.name == "socketsMain" }.configureEach {
            dependencies { implementation("io.ktor:ktor-network:3.0.3") }
        }
        val desktopTest by getting {
            dependencies {
                // Headless UI tests of the shared screens run on the JVM; the same composables run on every target.
                @OptIn(org.jetbrains.compose.ExperimentalComposeLibrary::class)
                implementation(compose.uiTest)
                implementation(compose.desktop.currentOs)
                implementation("org.jetbrains.kotlinx:kotlinx-coroutines-test:1.9.0")
            }
        }
        val desktopMain by getting {
            dependencies {
                implementation("org.jetbrains.kotlinx:kotlinx-coroutines-swing:1.9.0")
            }
        }
    }
}

