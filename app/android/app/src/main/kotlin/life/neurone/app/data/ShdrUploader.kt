package life.neurone.app.data

import life.neurone.core.analytics.WarrantyAnalyticsGate
import life.neurone.core.common.EncryptedKeyValueStore
import life.neurone.core.common.KeyValueStore
import java.security.SecureRandom
import okhttp3.CertificatePinner
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody

/**
 * Persistence seam for the opaque SHDR device token.
 *
 * Production is the app's sealed key-value store ([SealedDeviceTokenStore]);
 * tests supply an in-memory implementation so the OI-BLE-01 token logic (CSPRNG
 * fallback generation, hex encoding, 32-byte hub-token validation) is exercisable
 * on plain JVM without the Android Keystore — the same "privacy-critical logic must
 * be JVM-testable" principle the :core module follows. Production behavior is
 * unchanged: the token is still generated by SecureRandom and stored encrypted.
 */
interface DeviceTokenStore {
    /** The token kept for this helmet, or `null` if there is none. A token is per helmet, never per phone (REQ-SHDR-05). */
    fun load(hub: String): String?
    fun save(hub: String, token: String)
}

/**
 * The device token kept in a [KeyValueStore] that seals it (production: the app's `EncryptedKeyValueStore`, whose AES-256-GCM
 * sealing is the shared Rust core's and whose data key is wrapped by the Android Keystore). No Android crypto library is
 * involved, so the token is sealed the way the rest of the app's secrets are.
 */
class SealedDeviceTokenStore(private val store: KeyValueStore) : DeviceTokenStore {
    // One sealed value holds every helmet's token, a line each: `<hub>\t<token>`. A key per helmet would be a key the store
    // is not told to seal, so the map is kept inside the one that is. A value written before tokens were per helmet has no tab
    // on its line, so it reads as no helmet's token and is dropped on the next save.
    private fun read(): Map<String, String> =
        store.getString(ShdrUploader.TOKEN_PREF).orEmpty().lines()
            .mapNotNull { line -> line.split('\t').takeIf { it.size == 2 && it[0].isNotEmpty() && it[1].isNotEmpty() } }
            .associate { it[0] to it[1] }

    override fun load(hub: String): String? = read()[hub]

    override fun save(hub: String, token: String) {
        val all = read() + (hub to token)
        store.putString(ShdrUploader.TOKEN_PREF, all.entries.joinToString("\n") { "${it.key}\t${it.value}" })
    }
}

/**
 * SHDR fleet telemetry uploader — port of iOS SHDRUploader.swift.
 *
 * Consent subject: the WARRANTY OWNER (may be a clinic — CLAUDE.md §6.0).
 * Gated exclusively by [WarrantyAnalyticsGate]; this class must never
 * reference ConsentStore or ResearchAnalyticsGate (code-structural
 * independence of the two consent subjects).
 *
 * Device identity: an opaque locally generated 32-byte CSPRNG token stored
 * sealed (via [DeviceTokenStore]) — NEVER
 * ANDROID_ID, advertising ID, or any hardware identifier (parallel of the iOS
 * Keychain token replacing identifierForVendor, NP-PRIV-ANALYSIS-002 HIGH).
 * Upgraded to the hub-provisioned TRNG warranty token when the GATT
 * characteristic ships (OI-BLE-01 / OI-WA-03, NP-FW-EMMC-002 Rev A §A).
 *
 * Transport: TLS with SPKI SHA-256 certificate pinning (parallel of the iOS
 * SHDRFleetPinningDelegate). Replace the placeholder pins with hashes derived
 * from the production fleet endpoint certificates before deployment.
 */
class ShdrUploader(
    private val tokenStore: DeviceTokenStore,
    private val warrantyGate: WarrantyAnalyticsGate,
    private val client: OkHttpClient = defaultPinnedClient(),
) {
    companion object {
        const val FLEET_HOST = "fleet.neurone.life"
        const val FLEET_ENDPOINT = "https://$FLEET_HOST/v1/shdr"
        const val DEVICE_TOKEN_HEADER = "X-NP-Device-Token"
        internal const val TOKEN_PREF = EncryptedKeyValueStore.SHDR_DEVICE_TOKEN_KEY

        // PLACEHOLDERS — replace with production SPKI SHA-256 pins before deploy.
        private val PINNED_SPKI_HASHES = listOf(
            "sha256/AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=",
            "sha256/BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB=",
        )

        private fun defaultPinnedClient(): OkHttpClient =
            OkHttpClient.Builder()
                .certificatePinner(
                    CertificatePinner.Builder()
                        .apply { PINNED_SPKI_HASHES.forEach { add(FLEET_HOST, it) } }
                        .build(),
                )
                .build()
    }

    // Which helmet the link is to, `null` when not connected (privacy review Finding 6, REQ-SHDR-05).
    @Volatile
    private var hubIdentifier: String? = null

    /** The helmet the link is to, or `null` after a disconnect. Set by the wiring from the GATT manager. */
    fun setHubIdentifier(hub: String?) {
        hubIdentifier = hub
    }

    /**
     * Opaque device token for the connected helmet: generated once per helmet with SecureRandom, replaced by
     * [upgradeDeviceToken] when the hub provisions its TRNG token. Never per phone: a phone used with two helmets, or a clinic's
     * phone, would send one token for all of them. `null` when no helmet is connected, and then nothing is sent.
     */
    val deviceToken: String?
        get() {
            val hub = hubIdentifier ?: return null
            return tokenStore.load(hub) ?: run {
                val token = ByteArray(32).also { SecureRandom().nextBytes(it) }.toHex()
                tokenStore.save(hub, token)
                token
            }
        }

    /** OI-BLE-01: swap in the hub-provisioned TRNG warranty token (exactly 32 bytes) for the connected helmet. */
    fun upgradeDeviceToken(hubToken: ByteArray) {
        if (hubToken.size != 32) return
        val hub = hubIdentifier ?: return
        tokenStore.save(hub, hubToken.toHex())
    }

    /**
     * Upload an SHDR payload. No-ops unless the warranty owner has consented.
     * The payload is device telemetry only — the SHDR schema contains no user
     * biology by construction (CLAUDE.md §5.1); this class does not inspect it.
     */
    fun upload(shdrPayload: ByteArray, onResult: (Boolean) -> Unit) {
        if (!warrantyGate.isOpen) {
            onResult(false)
            return
        }
        val token = deviceToken
        if (token == null) {
            onResult(false)
            return
        }
        val request = Request.Builder()
            .url(FLEET_ENDPOINT)
            .header(DEVICE_TOKEN_HEADER, token)
            .post(shdrPayload.toRequestBody("application/octet-stream".toMediaType()))
            .build()
        client.newCall(request).enqueue(object : okhttp3.Callback {
            override fun onFailure(call: okhttp3.Call, e: java.io.IOException) = onResult(false)
            override fun onResponse(call: okhttp3.Call, response: okhttp3.Response) {
                response.use { onResult(it.isSuccessful) }
            }
        })
    }
}

private fun ByteArray.toHex(): String = joinToString("") { "%02x".format(it) }
